# 1. Установите elinks (на примере Ubuntu/Debian, команда может отличаться)
sudo apt-get install elinks

# 2. Запустите elinks и укажите адрес проблемной страницы
elinks https://chat.z.ai/c/ ...

# 3. Внутри elinks:
#    - Используйте стрелки для навигации.
#    - Найдите кнопку/ссылку для скачивания и нажмите Enter.
#    - Дождитесь, пока файл загрузится. Elinks спросит вас, куда его сохранить.
