/// Number of operand slots required by the crystallized function.
pub const N_OPERANDS: usize = 5;
/// Number of prefactor slots required by the crystallized function.
pub const N_PREFACTORS: usize = 7;

/// HRR-Bra index map: [m][entry] -> (na, nb, operand_idx)
/// For each m, lists all I(na, nb | m, 0) results
pub const HRR_BRA_MAP: &[[[usize; 3]]] = &[
    // m=0: [(na, nb, operand_idx), ...]
    &[
        [0, 0, 0],  // I(0, 0 | 0, 0)
        [1, 0, 1],  // I(1, 0 | 0, 0)
        [2, 0, 2],  // I(2, 0 | 0, 0)
        [0, 1, 3],  // I(0, 1 | 0, 0)
        [1, 1, 4],  // I(1, 1 | 0, 0)
    ],
];

/// HRR-Ket index map: [(nc, nd, operand_idx), ...]
/// Each entry is I(1, 1 | nc, nd)
pub const HRR_KET_MAP: &[[usize; 3]] = &[
    [0, 0, 4],  // I(1, 1 | 0, 0)
];

/// Crystallized ERI function for shell quartet (pp|ss).
/// Generated by POLER-ERI v3.2.0 VrrCrystallizer.
/// Gates: 4, Operands: 5, Prefactors: 7
/// nmax=2, mmax=0, rys_order=2, result_operand=4
/// Result: operands[4] = I(1,1,0,0)
///
/// Prefactor layout:
///   [0] c00  = PA_i (root-dependent: PA_i + t*PQ_i for Rys)
///   [1] c0p  = QC_i (root-dependent: QC_i + t*PQ_i for Rys)
///   [2] b10  = 1/(2p) (root-independent)
///   [3] b01  = 1/(2q) (root-independent)
///   [4] b00  = t/(2(p+q)) (root-dependent)
///   [5] -AB  = -(A_i - B_i) (root-independent)
///   [6] -CD  = -(C_i - D_i) (root-independent)
///
/// Caller: operands[0] = 1.0 (base case). Evaluate for each
/// Cartesian direction (x,y,z) and each Rys root, then compute
/// gx * gy * gz * weight and sum over roots.
#[inline(always)]
pub fn eri_ppss(operands: &mut [f64], prefactors: &[f64]) {
    debug_assert!(operands.len() >= N_OPERANDS, "operands slice too short: got {}, need {}", operands.len(), N_OPERANDS);
    debug_assert!(prefactors.len() >= N_PREFACTORS, "prefactors slice too short: got {}, need {}", prefactors.len(), N_PREFACTORS);
    // Gate 0: VRR-Bra [VRR-Bra: g[1][0] = c00 * g[0][0]]
    operands[1] = prefactors[0] * operands[0];
    // Gate 1: VRR-Bra [VRR-Bra: g[2][0] = c00*g[1][0] + 1*b10*g[0][0]]
    operands[2] = prefactors[0] * operands[1] + 1 * prefactors[2] * operands[0];
    // Gate 2: HRR-Bra [HRR-Bra: I(0,1)|0,0 from I(1,0|0,0) + AB*I(0,0|0,0) [m=0]]
    operands[3] = 1.0 * operands[1] + prefactors[5] * operands[0];
    // Gate 3: HRR-Bra [HRR-Bra: I(1,1)|0,0 from I(2,0|0,0) + AB*I(1,0|0,0) [m=0]]
    operands[4] = 1.0 * operands[2] + prefactors[5] * operands[1];
}
