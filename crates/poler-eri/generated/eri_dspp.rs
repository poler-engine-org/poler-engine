/// Crystallized ERI function for shell quartet (ds|pp).
/// Generated by POLER-ERI v3.2.0 VrrCrystallizer.
/// Gates: 12, Operands: 13, Prefactors: 7
/// nmax=2, mmax=2, rys_order=3, result_operand=12
/// Result: operands[12] = I(2,0,1,1)
///
/// Prefactor layout:
///   [0] c00  = PA_i (root-dependent: PA_i + t*PQ_i for Rys)
///   [1] c0p  = QC_i (root-dependent: QC_i + t*PQ_i for Rys)
///   [2] b10  = 1/(2p) (root-independent)
///   [3] b01  = 1/(2q) (root-independent)
///   [4] b00  = t/(2(p+q)) (root-dependent)
///   [5] -AB  = -(A_i - B_i) (root-independent)
///   [6] -CD  = -(C_i - D_i) (root-independent)
///
/// Caller: operands[0] = 1.0 (base case). Evaluate for each
/// Cartesian direction (x,y,z) and each Rys root, then compute
/// gx * gy * gz * weight and sum over roots.
#[inline(always)]
pub fn eri_dspp(operands: &mut [f64], prefactors: &[f64]) {
    debug_assert!(operands.len() >= N_OPERANDS, "operands slice too short: got {}, need {}", operands.len(), N_OPERANDS);
    debug_assert!(prefactors.len() >= N_PREFACTORS, "prefactors slice too short: got {}, need {}", prefactors.len(), N_PREFACTORS);
    // Gate 0: VRR-Bra [VRR-Bra: g[1][0] = c00 * g[0][0]]
    operands[1] = prefactors[0] * operands[0];
    // Gate 1: VRR-Bra [VRR-Bra: g[2][0] = c00*g[1][0] + 1*b10*g[0][0]]
    operands[2] = prefactors[0] * operands[1] + 1 * prefactors[2] * operands[0];
    // Gate 2: VRR-Ket [VRR-Ket: g[0][1] = c0p * g[0][0]]
    operands[3] = prefactors[1] * operands[0];
    // Gate 3: VRR-Ket [VRR-Ket: g[0][2] = c0p*g[0][1] + 1*b01*g[0][0]]
    operands[4] = prefactors[1] * operands[3] + 1 * prefactors[3] * operands[0];
    // Gate 4: VRR-Full [VRR-Full: g[1][1] = c00*g[0][1] + 1*b00*g[0][0]]
    operands[5] = prefactors[0] * operands[3] + 1 * prefactors[4] * operands[0];
    // Gate 5: VRR-Full [VRR-Full(p1): temp = c00*g[1][1] + 1*b10*g[0][1]]
    operands[9] = prefactors[0] * operands[5] + 1 * prefactors[2] * operands[3];
    // Gate 6: VRR-Full [VRR-Full(p2): g[2][1] = temp + 1*b00*g[1][0]]
    operands[6] = 1.0 * operands[9] + 1 * prefactors[4] * operands[1];
    // Gate 7: VRR-Full [VRR-Full: g[1][2] = c00*g[0][2] + 2*b00*g[0][1]]
    operands[7] = prefactors[0] * operands[4] + 2 * prefactors[4] * operands[3];
    // Gate 8: VRR-Full [VRR-Full(p1): temp = c00*g[1][2] + 1*b10*g[0][2]]
    operands[10] = prefactors[0] * operands[7] + 1 * prefactors[2] * operands[4];
    // Gate 9: VRR-Full [VRR-Full(p2): g[2][2] = temp + 2*b00*g[1][1]]
    operands[8] = 1.0 * operands[10] + 2 * prefactors[4] * operands[5];
    // Gate 10: HRR-Ket [HRR-Ket: I(2,0)|0,1) from I(2,0)|1,0) + CD*I(2,0)|0,0)]
    operands[11] = 1.0 * operands[6] + prefactors[6] * operands[2];
    // Gate 11: HRR-Ket [HRR-Ket: I(2,0)|1,1) from I(2,0)|2,0) + CD*I(2,0)|1,0)]
    operands[12] = 1.0 * operands[8] + prefactors[6] * operands[6];
}
