/// Crystallized ERI function for shell quartet (dd|ss).
/// Generated by POLER-ERI v3.2.0 VrrCrystallizer.
/// Gates: 11, Operands: 12, Prefactors: 7
/// nmax=4, mmax=0, rys_order=3, result_operand=11
/// Result: operands[11] = I(2,2,0,0)
///
/// Prefactor layout:
///   [0] c00  = PA_i (root-dependent: PA_i + t*PQ_i for Rys)
///   [1] c0p  = QC_i (root-dependent: QC_i + t*PQ_i for Rys)
///   [2] b10  = 1/(2p) (root-independent)
///   [3] b01  = 1/(2q) (root-independent)
///   [4] b00  = t/(2(p+q)) (root-dependent)
///   [5] -AB  = -(A_i - B_i) (root-independent)
///   [6] -CD  = -(C_i - D_i) (root-independent)
///
/// Caller: operands[0] = 1.0 (base case). Evaluate for each
/// Cartesian direction (x,y,z) and each Rys root, then compute
/// gx * gy * gz * weight and sum over roots.
#[inline(always)]
pub fn eri_ddss(operands: &mut [f64], prefactors: &[f64]) {
    debug_assert!(operands.len() >= N_OPERANDS, "operands slice too short: got {}, need {}", operands.len(), N_OPERANDS);
    debug_assert!(prefactors.len() >= N_PREFACTORS, "prefactors slice too short: got {}, need {}", prefactors.len(), N_PREFACTORS);
    // Gate 0: VRR-Bra [VRR-Bra: g[1][0] = c00 * g[0][0]]
    operands[1] = prefactors[0] * operands[0];
    // Gate 1: VRR-Bra [VRR-Bra: g[2][0] = c00*g[1][0] + 1*b10*g[0][0]]
    operands[2] = prefactors[0] * operands[1] + 1 * prefactors[2] * operands[0];
    // Gate 2: VRR-Bra [VRR-Bra: g[3][0] = c00*g[2][0] + 2*b10*g[1][0]]
    operands[3] = prefactors[0] * operands[2] + 2 * prefactors[2] * operands[1];
    // Gate 3: VRR-Bra [VRR-Bra: g[4][0] = c00*g[3][0] + 3*b10*g[2][0]]
    operands[4] = prefactors[0] * operands[3] + 3 * prefactors[2] * operands[2];
    // Gate 4: HRR-Bra [HRR-Bra: I(0,1)|0,0 from I(1,0|0,0) + AB*I(0,0|0,0) [m=0]]
    operands[5] = 1.0 * operands[1] + prefactors[5] * operands[0];
    // Gate 5: HRR-Bra [HRR-Bra: I(1,1)|0,0 from I(2,0|0,0) + AB*I(1,0|0,0) [m=0]]
    operands[6] = 1.0 * operands[2] + prefactors[5] * operands[1];
    // Gate 6: HRR-Bra [HRR-Bra: I(2,1)|0,0 from I(3,0|0,0) + AB*I(2,0|0,0) [m=0]]
    operands[7] = 1.0 * operands[3] + prefactors[5] * operands[2];
    // Gate 7: HRR-Bra [HRR-Bra: I(3,1)|0,0 from I(4,0|0,0) + AB*I(3,0|0,0) [m=0]]
    operands[8] = 1.0 * operands[4] + prefactors[5] * operands[3];
    // Gate 8: HRR-Bra [HRR-Bra: I(0,2)|0,0 from I(1,1|0,0) + AB*I(0,1|0,0) [m=0]]
    operands[9] = 1.0 * operands[6] + prefactors[5] * operands[5];
    // Gate 9: HRR-Bra [HRR-Bra: I(1,2)|0,0 from I(2,1|0,0) + AB*I(1,1|0,0) [m=0]]
    operands[10] = 1.0 * operands[7] + prefactors[5] * operands[6];
    // Gate 10: HRR-Bra [HRR-Bra: I(2,2)|0,0 from I(3,1|0,0) + AB*I(2,1|0,0) [m=0]]
    operands[11] = 1.0 * operands[8] + prefactors[5] * operands[7];
}
