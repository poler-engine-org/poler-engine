/// Crystallized ERI function for shell quartet (ss|dd).
/// Generated by POLER-ERI v3.2.0 VrrCrystallizer.
/// Gates: 11, Operands: 12, Prefactors: 7
/// nmax=0, mmax=4, rys_order=3, result_operand=11
/// Result: operands[11] = I(0,0,2,2)
///
/// Prefactor layout:
///   [0] c00  = PA_i (root-dependent: PA_i + t*PQ_i for Rys)
///   [1] c0p  = QC_i (root-dependent: QC_i + t*PQ_i for Rys)
///   [2] b10  = 1/(2p) (root-independent)
///   [3] b01  = 1/(2q) (root-independent)
///   [4] b00  = t/(2(p+q)) (root-dependent)
///   [5] -AB  = -(A_i - B_i) (root-independent)
///   [6] -CD  = -(C_i - D_i) (root-independent)
///
/// Caller: operands[0] = 1.0 (base case). Evaluate for each
/// Cartesian direction (x,y,z) and each Rys root, then compute
/// gx * gy * gz * weight and sum over roots.
#[inline(always)]
pub fn eri_ssdd(operands: &mut [f64], prefactors: &[f64]) {
    debug_assert!(operands.len() >= N_OPERANDS, "operands slice too short: got {}, need {}", operands.len(), N_OPERANDS);
    debug_assert!(prefactors.len() >= N_PREFACTORS, "prefactors slice too short: got {}, need {}", prefactors.len(), N_PREFACTORS);
    // Gate 0: VRR-Ket [VRR-Ket: g[0][1] = c0p * g[0][0]]
    operands[1] = prefactors[1] * operands[0];
    // Gate 1: VRR-Ket [VRR-Ket: g[0][2] = c0p*g[0][1] + 1*b01*g[0][0]]
    operands[2] = prefactors[1] * operands[1] + 1 * prefactors[3] * operands[0];
    // Gate 2: VRR-Ket [VRR-Ket: g[0][3] = c0p*g[0][2] + 2*b01*g[0][1]]
    operands[3] = prefactors[1] * operands[2] + 2 * prefactors[3] * operands[1];
    // Gate 3: VRR-Ket [VRR-Ket: g[0][4] = c0p*g[0][3] + 3*b01*g[0][2]]
    operands[4] = prefactors[1] * operands[3] + 3 * prefactors[3] * operands[2];
    // Gate 4: HRR-Ket [HRR-Ket: I(0,0)|0,1) from I(0,0)|1,0) + CD*I(0,0)|0,0)]
    operands[5] = 1.0 * operands[1] + prefactors[6] * operands[0];
    // Gate 5: HRR-Ket [HRR-Ket: I(0,0)|1,1) from I(0,0)|2,0) + CD*I(0,0)|1,0)]
    operands[6] = 1.0 * operands[2] + prefactors[6] * operands[1];
    // Gate 6: HRR-Ket [HRR-Ket: I(0,0)|2,1) from I(0,0)|3,0) + CD*I(0,0)|2,0)]
    operands[7] = 1.0 * operands[3] + prefactors[6] * operands[2];
    // Gate 7: HRR-Ket [HRR-Ket: I(0,0)|3,1) from I(0,0)|4,0) + CD*I(0,0)|3,0)]
    operands[8] = 1.0 * operands[4] + prefactors[6] * operands[3];
    // Gate 8: HRR-Ket [HRR-Ket: I(0,0)|0,2) from I(0,0)|1,1) + CD*I(0,0)|0,1)]
    operands[9] = 1.0 * operands[6] + prefactors[6] * operands[5];
    // Gate 9: HRR-Ket [HRR-Ket: I(0,0)|1,2) from I(0,0)|2,1) + CD*I(0,0)|1,1)]
    operands[10] = 1.0 * operands[7] + prefactors[6] * operands[6];
    // Gate 10: HRR-Ket [HRR-Ket: I(0,0)|2,2) from I(0,0)|3,1) + CD*I(0,0)|2,1)]
    operands[11] = 1.0 * operands[8] + prefactors[6] * operands[7];
}
