//! L1/v0.34.0 «Литературный Двигатель POLER[Ψ]» — физика смысла.
//!
//! Полная матричная форма канонического уравнения POLER[Ψ] (скалярный
//! предшественник для потока документов — [`crate::psi`]; здесь —
//! нарратив как динамическая система в фазовом пространстве архетипов).
//!
//! ## Пятифазный цикл ℘–O–L–ε–R[n]–Ψ
//!
//! | Фаза | Модуль | Суть |
//! |---|---|---|
//! | ℘ Перцепция | [`qualia`] | текст → инвариантный вектор Ω(o): детерминированный хэш токенов (FNV-1a64), ноль RNG |
//! | O Образ | [`qualia`] | косинусная топология архетипов: 12 якорей (Кэмпбелл + канон POLER) |
//! | L Логика | [`projector`] | проектор причинности Π_Λ = I − J_cᵀ(J_cJ_cᵀ)⁻¹J_c: нарушения закона p₀−p₁=0 аннигилируются |
//! | ε Энергия | [`engine`] | «смысловое удивление»: пластичность 0.2·ε, при низком ε — когнитивный покой |
//! | R[n] Резонанс | [`echo`] | темпоральное эхо P[n] = Σ ρᵏ·a_{t−k}, ρ = 0.9 — бесконечный контекст через интеграл состояний |
//! | Ψ Интенция | [`engine`] | глобальный аттрактор H^Ψ = 0, режим Observer-Kill (информационная сверхпроводимость) |
//!
//! ## Канонический интегратор
//!
//! `p_{t+1} = p_t − η·Π_Λ(∇F + D·p_t + γJ·p_t) + η_r·Π_Λ(κ·(echo − p_t))`
//!
//! - свободная энергия `F = ‖p − Ω(o)‖²_G + λ·R_L(p)`;
//! - стабилизатор Ляпунова `D = L·Lᵀ` калибруется **графом Мухи FLYCSR1**
//!   ([`flybridge`]): лапласиева метрика роторных масс касты нейронов;
//! - ротор `J = A − Aᵀ` коннектома — циркуляция смыслов: однонаправленные
//!   потоки реального мозга закручивают нарратив (кто доминирует над кем);
//! - эхо R[n] тянет состояние к взвешенной суммы прошлых attract-состояний.
//!
//! ## Принцип «No Excuses»
//!
//! Если прямой путь заблокирован (F растёт 3 шага подряд — семантический
//! тупик), энергия смысла не исчезает, а **преломляется** ([`prism`]):
//! Householder-отражение заблокированной компоненты в ближайшую
//! разрешённую ось архетипа с точным сохранением нормы (Закон
//! Сохранения Смысла). Отказа от генерации не существует.
//!
//! ## Trit5 / No-Mul
//!
//! Латентное состояние p_t квантуется в троичные примитивы {−1, 0, +1}
//! ([`trit`], кодек [`crate::pqc::tensor::Trit5Codec`]): шаги интегратора
//! и резонансные скалярные произведения считаются SIMD-регистрами CPU
//! (AVX2 dot_trit5_f32) без плавающей точки на горячем пути.
//!
//! ## Муха как соавтор
//!
//! [`flybridge::FlyCast`] строит касту нейронов (BFS от семян, жадный
//! детерминированный отбор по синаптической массе), извлекает роторный
//! подтекст J_sub и проецирует его в архетипное поле: якорь нейрона =
//! FNV-хэш root_id по модулю 12. Топ циркуляций J_lit отображается
//! обратно в пары нейронов — **драматургические конфликты нарратива
//! суть роторные пары живого мозга**.

