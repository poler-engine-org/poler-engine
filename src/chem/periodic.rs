/// Элемент по символу («Na», «CL» не допускается — регистр строгий).
pub fn by_symbol(sym: &str) -> Option<&'static Element> {
    ELEMENTS.iter().find(|e| e.symbol == sym)
}

/// Атомная масса по символу.
pub fn mass_of(sym: &str) -> Option<f64> {
    by_symbol(sym).map(|e| e.mass)
}

/// Элемент по Z.
pub fn by_z(z: u8) -> Option<&'static Element> {
    ELEMENTS.get(z as usize - 1).filter(|_| (1..=118).contains(&z))
}

/// Элемент по русскому имени (именительный или родительный падеж,
/// регистр не важен). Для SciVoice-разбора текстов задач.
pub fn by_name_ru(name: &str) -> Option<&'static Element> {
    let n = name.trim().to_lowercase();
    ELEMENTS.iter().find(|e| {
        (!e.name_ru.is_empty() && e.name_ru == n)
            || (!e.name_ru_gen.is_empty() && e.name_ru_gen == n)
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_integrity() {
        assert_eq!(ELEMENTS.len(), 118);
        for (i, e) in ELEMENTS.iter().enumerate() {
            assert_eq!(e.z as usize, i + 1, "Z нарушен у {}", e.symbol);
            assert!(e.mass > 0.0 && e.mass < 300.0, "масса {} {}", e.symbol, e.mass);
            // символ: 1-2 буквы, первая заглавная
            let b = e.symbol.as_bytes();
            assert!(b.len() == 1 || b.len() == 2);
            assert!(b[0].is_ascii_uppercase());
            if b.len() == 2 {
                assert!(b[1].is_ascii_lowercase());
            }
        }
    }

    #[test]
    fn lookup() {
        assert_eq!(by_symbol("H").unwrap().mass, 1.008);
        assert_eq!(by_symbol("Cl").unwrap().mass, 35.45);
        assert!(by_symbol("cl").is_none(), "регистр строгий");
        assert!(by_symbol("CL").is_none());
        assert_eq!(by_z(26).unwrap().symbol, "Fe");
        assert_eq!(by_name_ru("натрия").unwrap().symbol, "Na");
        assert_eq!(by_name_ru("Железо").unwrap().symbol, "Fe");
        assert_eq!(by_name_ru("кислорода").unwrap().symbol, "O");
    }

    #[test]
    fn school_crosscheck() {
        // школьные округления: Mg 24 против IUPAC 24.305 — худший случай
        // 1.3%, поэтому допуск 2% (округление учебника грубее 1%)
        let checks = [("Cl", 35.5), ("Cu", 64.0), ("Zn", 65.0), ("Fe", 56.0),
                      ("Mg", 24.0), ("Na", 23.0), ("S", 32.0), ("Ca", 40.0)];
        for (sym, school) in checks {
            let m = mass_of(sym).unwrap();
            assert!(
                (m - school).abs() / school < 0.02,
                "{sym}: {m} vs школьное {school}"
            );
        }
    }
}
