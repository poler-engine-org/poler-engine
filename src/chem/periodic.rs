/// Элемент таблицы.
pub struct Element {
    /// Порядковый номер.
    pub z: u8,
    /// Символ («H», «Na», «Cl»…).
    pub symbol: &'static str,
    /// Атомная масса (IUPAC 2021, conventional), а. е. м.
    pub mass: f64,
    /// Русское имя, именительный падеж («натрий»).
    pub name_ru: &'static str,
    /// Русское имя, родительный падеж («натрия») — для текстов
    /// «массовая доля …». Пусто у сверхтяжёлых.
    pub name_ru_gen: &'static str,
}

macro_rules! el {
    ($z:expr, $sym:expr, $mass:expr, $nom:expr, $gen:expr) => {
        Element { z: $z, symbol: $sym, mass: $mass, name_ru: $nom, name_ru_gen: $gen }
    };
}

