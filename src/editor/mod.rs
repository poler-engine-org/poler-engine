//! v0.38.0 poler-edit: суверенное ядро текстового редактора без лимитов.
//!
//! Архитектура (docs/POLER_EDIT.md):
//! * `buffer`   — Zero-Copy Piece-Table поверх mmap: файл любого размера
//!                открывается мгновенно, RAM не зависит от размера файла.
//! * `protocol` — JSON-протокол поверх stdio (LSP-стиль) для GUI-клиентов
//!                (integrations/poler-edit-qt): один процесс — много документов,
//!                события прогресса индексации/поиска, отмена длинных операций.
//! * `bench`    — --edit-bench: открытые цифры для питча (open ms, index GB/s,
//!                search GB/s, peak RSS).
//!
//! Слабости классических редакторов (Kate/KTextEditor, VS Code, gedit),
//! которые снимает это ядро:
//! 1. Лимит размера файла: поголовное выделение кучи под каждую строку
//!    (QList<KateLineLayout> и аналоги) взрывает RAM на гигабайтных логах.
//!    Здесь: mmap + кусочная таблица, чтение ленивое, только видимый вьюпорт.
//! 2. Долгое открытие: не читаем файл вообще — отображение окна за O(1).
//! 3. Поиск: SIMD Aho-Corasick прямо по mmap на скорости памяти,
//!    с корректным переносом совпадений через границы кусков правок.
//! 4. Undo: снапшоты кусочной таблицы (метаданные), а не копии текста.

pub mod bench;
pub mod buffer;
pub mod protocol;

