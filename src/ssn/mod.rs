//! S1/v0.35.0 «Синаптический Вихрь SSN» — доказанное ДО реализации ядро.
//!
//! Субстрат SSN извлечён из двух Google-Drive-архивов пользователя
//! (00_СИНАПТИЧЕСКАЯ_АРХИТЕКТУРА_SSN, 2174 диалога, 111 МБ + мегачаты
//! 573 тыс. строк): **226 уравнений и 109 алгоритмов** каталогизированы
//! в 5 отчётах (upload/gdrive/analysis/A…E). Затем — по директиве
//! «сначала доказать, убедиться, потом реализовать» — построен
//! верификационный набор проверок proofs/ssn_verify3.py: **65 проверок / 65 PASS**,
//! включая 10k-шаговую устойчивость полного стека и 12 найденных и
//! исправленных режимов отказа (F1–F12). Этот модуль — порт ДОКАЗАННОГО.
//!
//! ## Карта модуля
//!
//! | Модуль | Суть | Доказательство |
//! |---|---|---|
//! | [`vortex`] | Синаптический Вихрь: виртуальная топология (tgt = (i·39293 + f·29101 + seed·73471) mod N, ноль RAM на граф), фазовые синапсы cos(), латеральное торможение, STDP+DA, гомеостаз-интегратор (знак F2, след F8), E/I-контроллер, нейромодуляторы DA/5HT/NE, ритмы θ/γ | V17: 10k шагов → активность 4.9–5.5%, S<0.8, E/I≈4.4 |
//! | [`cse`] | Контекстно-семантический кодировщик: посимвольная фаза через золотое сечение φ | V8: зазор разделимости 1.353 (cos(a,b)=0.999 vs cos(a,c)=−0.355) |
//! | [`mindos`] | Операторы MindOS: NMDA-гейт (coincidence), WTA (k лидеров), Bind (интерполяция), модуляция с затуханием | V9: гейт 0.995/0.000, WTA ровно k, неравенство треугольника |
//! | [`transport`] | POLER-транспорт: Кэли-ротация (I−h/2·J)⁻¹(I+h/2·J), диссипация D, резонансное притяжение, SCTP-проектор Π = I − J_cᵀ(J_cJ_cᵀ)⁻¹J_c | V11: дрейф 3.7e-14; V18: ‖p‖=1, Σp=0, цикл; V13: Π идемпотентен |
//! | [`engine`] | Оркестратор: текст → CSE → инъекция → шаги → телеметрия + readout | интеграционные тесты |
//! | [`rng`] | xoshiro256** — детерминизм без внешних зависимостей | seed→траектория 1:1 |
//!
//! ## Ключевые уроки верификации (нельзя терять при переносе)
//!
//! - **F12**: ЕДИНОЕ определение активности — порог спайка a > 0.1
//!   (EQ-A23). Метрика с порогом 0.01 принимала здоровый субпороговый
//!   фон (a≈0.065) за «98% активность».
//! - **F2**: знак гомеостаза — гиперактивность ГАСИТ (w>0 ×(1−corr)),
//!   гипоактивность РАСТИТ. Ошибка знака = смерть сети.
//! - **F8**: гомеостаз действует на МЕДЛЕННЫЙ след f_sys (низкочастотный
//!   фильтр, интегральный контроллер), а не на мгновенную активность —
//!   иначе bang-bang перерегулирование.
//! - **F4**: транспорт ротации — только Кэли (2-й порядок); Эйлер дрейфует
//!   по норме даже на нормированной J (~1%/1000 шагов).
//! - **F6**: разделимость CSE даёт ТОЛЬКО золотая фаза (c·φ mod 2π);
//!   равномерная фаза — зазор 0.02 против 1.35.
//! - Цифровая эпилепсия (v1.0 исходных диалогов: 1M/1M нейронов горит)
//!   излечивается 20% GABA-нейронов + латеральным торможением;
//!   цифровая смерть — гомеостазом-интегратором.
//!
//! ## Золотые параметры (не трогать без повторного доказательства)
//!
//! homeo_k = 0.02, stdp_k = 0.0003, target = 5%, порог спайка 0.1,
//! шум σ = 0.015, спонтанная стимуляция 5%×1%, тормозных 20% (×−0.3),
//! R = N/100 (σ = R/2), мёртвая зона E/I [2,6], клипы медиаторов [0.1,0.9],
//! θ = 5 рад/с, γ = 40 рад/с, dt = 0.001.
//!
//! ## Режимы (из исходных диалогов: «Сыфрофой» = цифровая жизнь)
//!
//! Здоровый мозг: активность ~5% с лавинными флуктуациями (σ≈0.04 —
//! критичность, край хаоса), E/I ≈ 4, нейромодуляторы в коридоре.
//! Это НЕ равновесие — это устойчивая ДИНАМИКА: сеть живёт, шумит,
//! самоорганизуется. Полная противоположность и эпилепсии (S→1),
//! и смерти (activity→0).

