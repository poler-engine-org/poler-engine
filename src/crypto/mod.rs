//! Суверенная криптография POLER.
//!
//! `pnd` — C-ABI мост к Zig-ядру PND v8.2 (`os/core/poler_core.zig`),
//! собранному в `libpoler_core.a` (фича `pnd-ffi`, см. `build.rs`).
//!
//! Архитектурное место — уровень L0 единого инструмента
//! (`docs/UNIFIED_ARCHITECTURE.md`, M4): крипто-ядро под движком,
//! зависимость направлена строго вниз.
//!
//! M4.5 «Крипто-слой данных» (CDL) — криптография как **инструмент
//! работы с данными**, а не только защита (видение владельца):
//! - `hasher` — 256-битный детерминированный контент-хеш/MAC
//!   (pndMix/Φ + полный шифр): адресация чанков, дедупликация,
//!   целостность фактов без внешних библиотек;
//! - `kdf` — вывод 256-битного ключа Vault из парольной фразы
//!   (соль + итеративная прокачка шифром);
//! - `vault` — зашифрованный постоянный носитель памяти `.pvt`
//!   (страницы 4096 Б, CBC, цепной MAC, внешний SHA-256):
//!   документы/логи/чаты запечатываются «насмерть» и гоняются
//!   через git без ключа (проверяемо) и с ключом (читаемо).

