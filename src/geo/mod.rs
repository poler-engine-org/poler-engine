//! GIS-ядро poler-engine на тритных координатах (Сессия-12).
//!
//! Порт Geo/GIS-движков (georust/geo, rstar, spade, h3 — исходники в
//! `scripts/geo_research/*.poler`, см. PORTING_NOTES.md) на
//! сбалансированно-троичное представление. Тритная парадигма:
//!
//! * **координаты** — тритные числа на решётке с квантом 3⁻ᵏ
//!   ([`trit_coord`]): все предикаты целочисленно точны, без epsilon;
//! * **топология** — DE-9IM сжата в 9-тритное число ([`de9im`]):
//!   ячейка {−1 пусто, 0 точка, +1 линия-и-больше} = проекции спина-1,
//!   трит = кутрит;
//! * **изоповерхности** — marching tetrahedra с самокорректирующейся
//!   таблицей ([`marching`]): рельеф Этерии и фредеритовые поля
//!   в объёмном рендере viz-ядра.
//!
//! Слои (план PORTING_NOTES.md): geo-types-ядро → DE-9IM → 27-дерево →
//! H3-гексагоны → рендер. Эта сессия закрывает первые два + изоповерхности.
//!
//! ```text
//! f64-мир ──квантование 3⁻ᵏ──▶ тритная решётка ──точные знаки──▶ DE-9IM
//!                                   │
//! воксельные поля ──marching tetra──▶ треугольники ──viz_iso3──▶ SVG
//! ```

