//! GIS-ядро poler-engine на тритных координатах (Сессии 12+14).
//!
//! Порт Geo/GIS-движков (georust/geo, rstar, spade, h3 — исходники в
//! `scripts/geo_research/*.poler`, см. PORTING_NOTES.md) на
//! сбалансированно-троичное представление. Тритная парадигма:
//!
//! * **координаты** — тритные числа на решётке с квантом 3⁻ᵏ
//!   ([`trit_coord`]): все предикаты целочисленно точны, без epsilon;
//! * **топология** — DE-9IM сжата в 9-тритное число ([`de9im`]):
//!   ячейка {−1 пусто, 0 точка, +1 линия-и-больше} = проекции спина-1,
//!   трит = кутрит; Сессия-14 — строки: relate LineString×Polygon;
//! * **изоповерхности** — marching tetrahedra с самокорректирующейся
//!   таблицей ([`marching`]): рельеф Этерии и фредеритовые поля
//!   в объёмном рендере viz-ядра;
//! * **27-дерево** ([`tree27`], Сессия-14) — тритное деление 3×3×3 XYZ
//!   вместо октодерева: путь к ячейке — чистая тритная запись (3 трита
//!   на уровень);
//! * **гекс-сетка** ([`hexgrid`], Сессия-14) — мини-H3: осевые
//!   координаты, трит-спираль в 6-тритном блоке (729 состояний, диски
//!   до R=13), икосаэдр 20 граней — адрес мира = 9 тритов;
//! * **мир Этерии** ([`eteria`], Сессия-14) — diamond-square рельеф,
//!   биомы, гекс-карта и больцмановское переплетение с LogProb:
//!   Z = Σ e^(−E_i) при E_i ~ 1e5 — весь ряд за пределами f64.
//!
//! Слои (план PORTING_NOTES.md): geo-types-ядро → DE-9IM → 27-дерево →
//! H3-гексагоны → рендер. Сессии 12+14 закрывают план целиком: ядро,
//! топология (+строки), изоповерхности, индекс, гексы, мир.
//!
//! ```text
//! f64-мир ──квантование 3⁻ᵏ──▶ тритная решётка ──точные знаки──▶ DE-9IM
//!                                   │
//! воксельные поля ──marching tetra──▶ треугольники ──viz_iso3──▶ SVG
//!                                   │
//! XYZ-конверты ──27-дерево (3×3×3)──▶ трит-пути «++0·−0+·…»──▶ O(log₂₇ N)
//!                                   │
//! икосаэдр+гексы ──трит-спираль 6 тритов──▶ мир 9 тритов ──▶ биомы Этерии
//!                                   │
//! высоты → E_i ──e^(−E_i)──▶ LogProb ──lpsum──▶ Z за пределами f64
//! ```

