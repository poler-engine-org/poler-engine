//! # P³-Мост (цикл R, v0.53.0)
//!
//! Живое соединение POLER ENGINE (Rust) и P³ Engine (Zig) через C-ABI.
//!
//! ```text
//!   POLER ENGINE (Rust)                P³ ENGINE (Zig)
//!   ───────────────────                ────────────────
//!   p3::native   p3::ffi   ──dlopen──▶ libp3ffi.so
//!   (математика-близнец)              (p3_ffi.zig поверх p3_kernel)
//!          │                                │
//!          └────────── p3::conformance ─────┘
//!              (общие фикстуры, честность f64)
//!
//!   p3::render: гамильтониан ─▶ эволюция ─▶ тройной буфер ─▶ PNG
//!   (POLER считает, P³ рендерит — «кадр из гамильтониана»)
//! ```
//!
//! Гарантии:
//! - Rust-близнец (`native`) реализует ту же математику, что и ядро
//!   P³; конформанс проверяется на общих фикстурах (данные идут
//!   через FFI, PRNG один — расхождений «по построению» нет).
//! - Рендер детерминирован: одинаковый вход → байт-в-байт тот же PNG.
//! - Библиотека ищется по списку путей (env, рядом с бинарником,
//!   `ffi/` репозитория); ABI проверяется при загрузке.

